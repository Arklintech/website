// Generates src/components/brand/wordmark-glyphs.ts — the outlined vector
// geometry of "RKLINTECH" taken directly from Syncopate Bold, the exact font
// face the site renders the wordmark with. Outlining (rather than setting text)
// makes the logo independent of web-font loading and pins its geometry.
//
// Usage: node scripts/generate-wordmark-glyphs.mjs

import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const fontkit = require('@pdf-lib/fontkit');

// Syncopate Bold (latin subset) as served by Google Fonts — same file the site loads.
const FONT_URL = 'https://fonts.gstatic.com/s/syncopate/v24/pe0pMIuPIYBCpEV5eFdKvtKqBP5v.woff2';
const LETTERS = 'RKLINTECH';
const OUT = path.resolve('src/components/brand/wordmark-glyphs.ts');

const round = (n) => Math.round(n * 100) / 100;

// Font outlines are y-up; SVG is y-down. Flip y so the baseline sits at y = 0.
function toSvgPath(glyph) {
  return glyph.path.commands
    .map(({ command, args }) => {
      const pts = [];
      for (let i = 0; i < args.length; i += 2) pts.push(`${round(args[i])} ${round(-args[i + 1])}`);
      switch (command) {
        case 'moveTo': return `M${pts[0]}`;
        case 'lineTo': return `L${pts[0]}`;
        case 'quadraticCurveTo': return `Q${pts.join(' ')}`;
        case 'bezierCurveTo': return `C${pts.join(' ')}`;
        case 'closePath': return 'Z';
        default: throw new Error(`Unsupported path command: ${command}`);
      }
    })
    .join('');
}

const res = await fetch(FONT_URL);
if (!res.ok) throw new Error(`Font download failed: ${res.status}`);
const font = fontkit.create(Buffer.from(await res.arrayBuffer()));
if (font.fullName !== 'Syncopate Bold') throw new Error(`Unexpected font: ${font.fullName}`);

const run = font.layout(LETTERS);
const glyphs = run.glyphs.map((glyph, i) => ({
  char: LETTERS[i],
  advance: run.positions[i].xAdvance,
  inkRight: glyph.bbox.maxX,
  d: toSvgPath(glyph),
}));

const body = `// AUTO-GENERATED by scripts/generate-wordmark-glyphs.mjs — do not edit by hand.
// Outlined "RKLINTECH" from ${font.fullName} (${font.unitsPerEm} units/em), y-down, baseline at y = 0.

export const WORDMARK_FONT_METRICS = {
  unitsPerEm: ${font.unitsPerEm},
  ascent: ${font.ascent},
  descent: ${Math.abs(font.descent)},
  capHeight: ${font.capHeight},
} as const;

export const WORDMARK_GLYPHS: ReadonlyArray<{ char: string; advance: number; inkRight: number; d: string }> = ${JSON.stringify(glyphs, null, 2)};
`;

fs.writeFileSync(OUT, body, 'utf-8');
console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${glyphs.length} glyphs)`);
